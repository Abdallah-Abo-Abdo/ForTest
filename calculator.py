import matplotlib.pyplot as plt  # استيراد مكتبة الرسم البياني

# ============================================================
# بيانات مثال بسيطة
# ============================================================
# هذه القيم ستمثل المحور الأفقي (X)
x = [1, 2, 3, 4, 5]

# هذه القيم ستمثل المحور العمودي (Y)
# كل قيمة في Y تقابل قيمة في X
y = [2, 4, 6, 8, 10]

# ============================================================
# رسم الخط البياني
# ============================================================
# يرسم علاقة بين x و y على شكل خط
plt.plot(x, y)

# ============================================================
# إضافة تسميات للمحاور
# ============================================================
plt.xlabel("X Axis")   # اسم المحور الأفقي
plt.ylabel("Y Axis")   # اسم المحور العمودي

# ============================================================
# إضافة عنوان للرسم
# ============================================================
plt.title("Simple Line Plot")

# ============================================================
# عرض الرسم على الشاشة
# ============================================================
plt.show()